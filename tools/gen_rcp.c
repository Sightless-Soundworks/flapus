/* Generates src/enc_rcp_tables.c: Intel's rcpps and rsqrtps as lookup tables.

   rcpps and rsqrtps are approximations (relative error up to 1.5*2^-12) whose exact
   bits are up to the CPU: AMD gives other values than Intel. The CELT PVQ search uses
   them, so without the tables the output depends on the CPU maker. On an Intel Core
   i7-13700K the result depends only on the top 11 mantissa bits of the input for
   rcpps, and on the top 10 plus the exponent parity for rsqrtps, and it has 12
   significant bits. Two tables of 2048 entries therefore reproduce the instructions,
   and FLAPUS_PORTABLE_MATH uses them instead of the hardware.

   Run on an Intel CPU:  gcc -O2 -msse2 -I.. -o gen_rcp gen_rcp.c && ./gen_rcp > ../src/enc_rcp_tables.c
   It checks the emulation against the hardware for all 2^32 inputs of both
   instructions before it writes anything, and fails if a single one differs. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <xmmintrin.h>

static unsigned tab_rcp[2048], tab_rsqrt[2048];

static unsigned bits(float f) { unsigned u; memcpy(&u, &f, 4); return u; }
static float flt(unsigned u) { float f; memcpy(&f, &u, 4); return f; }
static unsigned hw(int rs, unsigned in) {
   __m128 v = _mm_set_ss(flt(in));
   v = rs ? _mm_rsqrt_ss(v) : _mm_rcp_ss(v);
   return bits(_mm_cvtss_f32(v));
}

/* The emulation, as in src/enc_rcp_tables.c (kept identical by hand). */
static unsigned emu_rcp(unsigned x) {
   unsigned s = x & 0x80000000u, e = (x >> 23) & 0xff, t;
   int re;
   if (e == 0) return s | 0x7f800000u;                         /* 0, subnormal: inf */
   if (e == 0xff) return (x & 0x7fffff) ? x | 0x400000u : s;   /* NaN quiet, inf: 0 */
   t = tab_rcp[(x >> 12) & 0x7ff];
   re = (int)(t >> 12)+126+127-(int)e;
   if (re <= 0) return s;                                      /* subnormal result: 0 */
   return s | (unsigned)re << 23 | (t & 0xfff) << 11;
}
static unsigned emu_rsqrt(unsigned x) {
   unsigned e = (x >> 23) & 0xff, t;
   int k, re;
   if (e == 0) return (x & 0x80000000u) | 0x7f800000u;         /* +-0, subnormal: +-inf */
   if (e == 0xff) {
      if (x & 0x7fffff) return x | 0x400000u;                  /* NaN quiet */
      return (x & 0x80000000u) ? 0xffc00000u : 0;              /* -inf: NaN, +inf: 0 */
   }
   if (x & 0x80000000u) return 0xffc00000u;                    /* negative: NaN */
   k = ((int)e-127) >> 1;                                      /* x = 4^k * [1,4) */
   t = tab_rsqrt[((e-127) & 1) << 10 | ((x >> 13) & 0x3ff)];
   re = (int)(t >> 12)+126-k;
   return (unsigned)re << 23 | (t & 0xfff) << 11;
}

int main(void) {
   unsigned i, n, bad = 0;
   unsigned long long u;
   for (i = 0; i < 2048; i++) {
      unsigned r = hw(0, 127u << 23 | i << 12);
      if ((r & 0x7ff) || ((r >> 23) != 126 && (r >> 23) != 127)) { fprintf(stderr, "rcp layout %u: %08x\n", i, r); return 1; }
      tab_rcp[i] = ((r >> 23)-126) << 12 | ((r >> 11) & 0xfff);
   }
   for (i = 0; i < 2048; i++) {
      unsigned r = hw(1, (127u+(i >> 10)) << 23 | (i & 0x3ff) << 13);
      if ((r & 0x7ff) || ((r >> 23) != 126 && (r >> 23) != 127)) { fprintf(stderr, "rsqrt layout %u: %08x\n", i, r); return 1; }
      tab_rsqrt[i] = ((r >> 23)-126) << 12 | ((r >> 11) & 0xfff);
   }
   for (u = 0; u <= 0xffffffffull; u++) {
      unsigned x = (unsigned)u;
      if (hw(0, x) != emu_rcp(x) && bad++ < 10) fprintf(stderr, "rcp %08x: hw %08x emu %08x\n", x, hw(0, x), emu_rcp(x));
      if (hw(1, x) != emu_rsqrt(x) && bad++ < 10) fprintf(stderr, "rsqrt %08x: hw %08x emu %08x\n", x, hw(1, x), emu_rsqrt(x));
   }
   if (bad) { fprintf(stderr, "%u mismatches; nothing written\n", bad); return 1; }
   fprintf(stderr, "all 2^32 inputs of rcpss and rsqrtss match the emulation\n");
   printf("/* ---- Intel rcpps/rsqrtps as tables (FLAPUS_PORTABLE_MATH), generated by tools/gen_rcp.c ----\n"
          "   Entry: bit 12 = result exponent - 126 for an input in [1,2) (rsqrt: [1,4)),\n"
          "   bits 0-11 = the 12 result mantissa bits below the 11 that are always zero. Checked\n"
          "   against an Intel Core i7-13700K for all 2^32 inputs of both instructions. */\n"
          "#ifdef FLAPUS_PORTABLE_MATH\n");
   for (n = 0; n < 2; n++) {
      unsigned *t = n ? tab_rsqrt : tab_rcp;
      printf("static const unsigned short fl_%s_tab[2048] = {", n ? "rsqrt" : "rcp");
      for (i = 0; i < 2048; i++) printf("%s0x%04x,", i % 12 ? " " : "\n   ", t[i]);
      printf("\n};\n");
   }
   printf("#endif /* FLAPUS_PORTABLE_MATH */\n");
   return 0;
}
